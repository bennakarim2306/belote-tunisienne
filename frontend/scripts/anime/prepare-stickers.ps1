# LOCAL dev script: one character's 8 chat stickers -> app assets, then regenerates
# src/anime/stickers.ts from every sticker file present (so adding a character is
# just: run this script again with the next folder).
#   powershell.exe -ExecutionPolicy Bypass -File scripts\anime\prepare-stickers.ps1 -SourceDir <folder> -Avatar av12
# (Windows PowerShell 5.1.) <folder> holds "<n>_<msgId>.png" or any file whose name
# starts with "<n> - " (n = 1..8 in the order below).
param(
  [Parameter(Mandatory = $true)][string]$SourceDir,
  [Parameter(Mandatory = $true)][ValidatePattern("^av\d{1,2}$")][string]$Avatar
)
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent (Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path))
$outDir = Join-Path $root "assets\anime\stickers"; New-Item -ItemType Directory -Force $outDir | Out-Null
# same order as CHAT_MSGS in app/game/[id].tsx and the prompts
$ids = @("wellPlayed", "yezzi", "aychek", "luck", "yalla", "oops", "sahha", "thinking")
Add-Type -AssemblyName System.Drawing
Add-Type -ReferencedAssemblies System.Drawing -TypeDefinition @"
using System;
using System.Drawing;
using System.Drawing.Drawing2D;
using System.Drawing.Imaging;
using System.Runtime.InteropServices;
public static class StickerAssets {
  public static Bitmap Clean(Bitmap src, int cut, int solid) {
    int w = src.Width, h = src.Height;
    Bitmap bmp = src.Clone(new Rectangle(0, 0, w, h), PixelFormat.Format32bppArgb);
    BitmapData d = bmp.LockBits(new Rectangle(0, 0, w, h), ImageLockMode.ReadWrite, PixelFormat.Format32bppArgb);
    byte[] px = new byte[d.Stride * h];
    Marshal.Copy(d.Scan0, px, 0, px.Length);
    int minX = w, minY = h, maxX = -1, maxY = -1;
    for (int y = 0; y < h; y++) {
      int row = y * d.Stride;
      for (int x = 0; x < w; x++) {
        int i = row + x * 4;
        int a = px[i + 3];
        if (a < cut) { px[i] = 0; px[i + 1] = 0; px[i + 2] = 0; px[i + 3] = 0; continue; }
        if (a >= solid) px[i + 3] = 255;
        if (x < minX) minX = x; if (x > maxX) maxX = x;
        if (y < minY) minY = y; if (y > maxY) maxY = y;
      }
    }
    Marshal.Copy(px, 0, d.Scan0, px.Length);
    bmp.UnlockBits(d);
    // square canvas around the content, content centred
    int cw = maxX - minX + 1, ch = maxY - minY + 1, side = Math.Max(cw, ch);
    Bitmap sq = new Bitmap(side, side, PixelFormat.Format32bppArgb);
    using (Graphics g = Graphics.FromImage(sq)) {
      g.Clear(Color.Transparent);
      g.DrawImage(bmp, new Rectangle((side - cw) / 2, side - ch, cw, ch), minX, minY, cw, ch, GraphicsUnit.Pixel);
    }
    bmp.Dispose();
    return sq;
  }
  public static Bitmap Resize(Bitmap src, int w, int h) {
    Bitmap dst = new Bitmap(w, h, PixelFormat.Format32bppArgb);
    using (Graphics g = Graphics.FromImage(dst)) {
      g.CompositingMode = CompositingMode.SourceCopy;
      g.CompositingQuality = CompositingQuality.HighQuality;
      g.InterpolationMode = InterpolationMode.HighQualityBicubic;
      g.PixelOffsetMode = PixelOffsetMode.HighQuality;
      g.DrawImage(src, new Rectangle(0, 0, w, h), 0, 0, src.Width, src.Height, GraphicsUnit.Pixel);
    }
    return dst;
  }
}
"@
$files = Get-ChildItem -LiteralPath $SourceDir -Filter *.png
for ($n = 1; $n -le 8; $n++) {
  $f = $files | Where-Object { $_.Name -match "^$n(_| - )" } | Select-Object -First 1
  if (-not $f) { throw "sticker $n ($($ids[$n - 1])) not found in $SourceDir" }
  $raw = New-Object System.Drawing.Bitmap $f.FullName
  $sq = [StickerAssets]::Clean($raw, 96, 238)
  # 256 px covers an ~84 dp sticker at 3x density; keeps 12 characters x 8 stickers reasonable
  $small = [StickerAssets]::Resize($sq, 256, 256)
  $p = Join-Path $outDir "$($Avatar)_$($ids[$n - 1]).png"
  $small.Save($p, [System.Drawing.Imaging.ImageFormat]::Png)
  "{0,-26} <- {1}  {2} KB" -f (Split-Path $p -Leaf), $f.Name, [int]((Get-Item $p).Length / 1KB)
  $raw.Dispose(); $sq.Dispose(); $small.Dispose()
}

# ---- regenerate src/anime/stickers.ts (require() paths must be literal) ----
$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("// GENERATED by scripts/anime/prepare-stickers.ps1 - do not edit by hand.")
$lines.Add("// Chat stickers per avatar id and quick-chat message id (anime theme only).")
$lines.Add('import { ImageSourcePropType } from "react-native";')
$lines.Add("")
$lines.Add("export const STICKERS: Record<string, Record<string, ImageSourcePropType>> = {")
$byAvatar = Get-ChildItem $outDir -Filter "av*_*.png" | Group-Object { $_.BaseName.Split("_")[0] } | Sort-Object { [int]($_.Name.Substring(2)) }
foreach ($g in $byAvatar) {
  $lines.Add("  $($g.Name): {")
  foreach ($id in $ids) {
    $file = "$($g.Name)_$id.png"
    if ($g.Group.Name -contains $file) { $lines.Add("    ${id}: require(`"../../assets/anime/stickers/$file`"),") }
  }
  $lines.Add("  },")
}
$lines.Add("};")
$ts = Join-Path $root "src\anime\stickers.ts"
[IO.File]::WriteAllText($ts, ($lines -join "`n") + "`n")
"stickers.ts: " + (($byAvatar | ForEach-Object { "$($_.Name) ($($_.Count))" }) -join ", ")
