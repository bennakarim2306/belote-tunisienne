export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("fr");

  useEffect(() => {
    // never force native RTL — we mirror manually where needed
    try {
      I18nManager.allowRTL(false);
    } catch {}
    storage.getItem("lang", "fr").then((v) => {
      if (v === "ar" || v === "fr" || v === "en") setLangState(v);
    });
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    storage.setItem("lang", l);
  }, []);

  const t = useCallback(
    (key: TKey, vars?: Record<string, string | number>) => {
      let s: string = translations[lang][key] ?? translations.fr[key] ?? key;
      if (vars) {
        Object.entries(vars).forEach(([k, v]) => {
          s = s.split(`{${k}}`).join(String(v));
        });
      }
      return s;
    },
    [lang],
  );

  const value = useMemo(
    () => ({ lang, setLang, t, isRTL: lang === "ar" }),
    [lang, setLang, t],
  );

  return (
    <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
  );
}

export const useI18n = () => useContext(LanguageContext);
